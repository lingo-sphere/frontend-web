interface IconProps {
  name: string;
  size?: number;
  className?: string;
  strokeWidth?: number;
}

const toCamelCase = (str: string) =>
  str.replace(/-([a-z0-9])/g, (_, g) => g.toUpperCase());

export function Icon({
  name,
  size = 18,
  className,
  strokeWidth = 1.8,
}: IconProps) {
  const IconComponent = iconMap[name] || iconMap[toCamelCase(name)];
  if (!IconComponent) return null;
  return (
    <IconComponent
      aria-hidden="true"
      className={className}
      size={size}
      strokeWidth={strokeWidth}
    />
  );
}
