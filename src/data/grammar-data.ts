export function getGrammarPointsByType(type: GrammarType): GrammarPoint[] {
  return grammarPoints.filter((g) => g.grammarType === type && g.status === 'ACTIVE')
}

export function getGrammarPointsByLevel(level: CEFRLevel): GrammarPoint[] {
  return grammarPoints.filter((g) => g.cefrLevel === level && g.status === 'ACTIVE')
}

export function getFeaturedGrammarPoints(): GrammarPoint[] {
  return grammarPoints.filter((g) => g.isFeatured && g.status === 'ACTIVE')
}

export function getGrammarExamples(grammarPointId: string): GrammarExample[] {
  return grammarExamples.filter(
    (e) => e.grammarPointId === grammarPointId && e.status === 'ACTIVE'
  )
}

export function searchGrammarPoints(query: string): GrammarPoint[] {
  const lowerQuery = query.toLowerCase()
  return grammarPoints.filter(
    (g) =>
      g.status === 'ACTIVE' &&
      (g.nameEn.toLowerCase().includes(lowerQuery) ||
        g.nameVi.toLowerCase().includes(lowerQuery) ||
        g.descriptionEn.toLowerCase().includes(lowerQuery) ||
        g.descriptionVi.toLowerCase().includes(lowerQuery))
  )
}

export function getGrammarPointById(id: string): GrammarPoint | undefined {
  return grammarPoints.find((g) => g.id === id)
}

