export function getUnreadCount(notifications: Notification[]): number {
  return notifications.filter((n) => !n.isRead).length
}

export function getNotificationsByCategory(notifications: Notification[], category: string): Notification[] {
  return notifications.filter((n) => n.notificationCategory === category)
}

export function markAsRead(notifications: Notification[], id: string): Notification[] {
  return notifications.map((n) =>
    n.id === id ? { ...n, isRead: true, readAt: new Date().toISOString() } : n
  )
}

export function markAllAsRead(notifications: Notification[]): Notification[] {
  const now = new Date().toISOString()
  return notifications.map((n) => (n.isRead ? n : { ...n, isRead: true, readAt: now }))
}

export function getPinnedNotifications(notifications: Notification[]): Notification[] {
  return notifications.filter((n) => n.isPinned)
}
